#!/usr/bin/env bash
# Fetches Cloudflare's published IP ranges, then:
#  1. regenerates nginx's real_ip config so $remote_addr is the visitor, not Cloudflare;
#  2. allows 443/tcp in ufw from those ranges only (origin is unreachable except via Cloudflare).
# Installed as /usr/local/sbin/smiley-update-cloudflare-ips; run weekly by cloudflare-ips.timer.
set -euo pipefail

CONF=/etc/nginx/conf.d/cloudflare-realip.conf
V4_RE='([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}'
V6_RE='[0-9a-fA-F:]+/[0-9]{1,3}'

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

fetch() {  # url file regex — refuses to continue on anything that is not a CIDR list
  # The trailing echo matters: Cloudflare's lists lack a final newline, and without it
  # concatenating v4 + v6 would fuse the last v4 range with the first v6 range.
  { curl -fsS --max-time 30 "$1"; echo; } | tr -d '\r' | sed '/^[[:space:]]*$/d' > "$2"
  if grep -qvxE "$3" "$2" || [ "$(wc -l < "$2")" -lt 3 ]; then
    echo "Unexpected response from $1; leaving configuration unchanged." >&2
    exit 1
  fi
}
fetch https://www.cloudflare.com/ips-v4 "$tmp/v4" "$V4_RE"
fetch https://www.cloudflare.com/ips-v6 "$tmp/v6" "$V6_RE"
cat "$tmp/v4" "$tmp/v6" | sort -u > "$tmp/all"

# --- nginx real_ip ---
{
  echo "# Generated by smiley-update-cloudflare-ips. Do not edit."
  sed 's/.*/set_real_ip_from &;/' "$tmp/all"
  echo "real_ip_header CF-Connecting-IP;"
} > "$tmp/realip.conf"

if ! cmp -s "$tmp/realip.conf" "$CONF"; then
  [ -f "$CONF" ] && cp "$CONF" "$tmp/realip.conf.bak"
  install -m 644 "$tmp/realip.conf" "$CONF"
  if nginx -t 2>/dev/null; then
    systemctl is-active --quiet nginx && systemctl reload nginx
    echo "nginx real_ip ranges updated."
  else
    if [ -f "$tmp/realip.conf.bak" ]; then install -m 644 "$tmp/realip.conf.bak" "$CONF"; else rm -f "$CONF"; fi
    echo "nginx rejected the new config; restored previous version." >&2
    exit 1
  fi
fi

# --- ufw: 443 from Cloudflare only ---
if command -v ufw >/dev/null; then
  ufw show added | grep "comment 'cloudflare'" | grep -oE 'from [^ ]+' | cut -d' ' -f2 | sort -u > "$tmp/current" || true
  comm -13 "$tmp/current" "$tmp/all" | while read -r cidr; do
    ufw allow proto tcp from "$cidr" to any port 443 comment 'cloudflare' >/dev/null
  done
  comm -23 "$tmp/current" "$tmp/all" | while read -r cidr; do
    ufw delete allow proto tcp from "$cidr" to any port 443 >/dev/null
  done
  echo "ufw: $(wc -l < "$tmp/all") Cloudflare ranges allowed on 443/tcp."
fi
