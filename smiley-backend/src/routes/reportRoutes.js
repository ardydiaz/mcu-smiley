import { Router } from 'express';
import { report, exportCsv, sendTeamsDigestNow } from '../controllers/reportController.js';
import { requireAuth, requirePermission } from '../middleware/authMiddleware.js';
import { validate } from '../middleware/validationMiddleware.js';
import { filterSchema } from '../validations/voteValidation.js';
const router = Router();
router.use(requireAuth, requirePermission('reports'));
router.get('/', validate(filterSchema, 'query'), report);
router.get('/csv', validate(filterSchema, 'query'), exportCsv);
router.post('/teams-digest/send', sendTeamsDigestNow);
export default router;
