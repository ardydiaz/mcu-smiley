import { Router } from 'express';
import { rateLimit } from 'express-rate-limit';
import { completeSso, getSsoConfig, kioskMe, listUsers, login, me, register, startSso, updateUserAccess } from '../controllers/authController.js';
import { authMiddleware, requireAuth, requireKioskAuth } from '../middleware/authMiddleware.js';
import { auditLog } from '../middleware/auditLogMiddleware.js';
import { validate, idSchema } from '../middleware/validationMiddleware.js';
import { loginSchema, registerSchema, userAccessSchema } from '../validations/authValidation.js';
const router = Router();
const ssoLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 20, standardHeaders: 'draft-8', legacyHeaders: false, message: { success: false, message: 'Too many SSO attempts; try again later' } });
router.post('/register', rateLimit({ windowMs: 15 * 60 * 1000, limit: 5, standardHeaders: 'draft-8', legacyHeaders: false, message: { success: false, message: 'Too many registration attempts; try again later' } }), validate(registerSchema), register);
router.post('/login', rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: 'draft-8', legacyHeaders: false, message: { success: false, message: 'Too many login attempts; try again later' } }), validate(loginSchema), login);
router.get('/sso/config', getSsoConfig);
router.get('/sso/start', ssoLimiter, startSso);
router.get('/sso/callback', completeSso);
router.get('/microsoft/start', ssoLimiter, startSso);
router.get('/microsoft/callback', completeSso);
router.get('/me', requireAuth, me);
router.get('/kiosk/me', requireKioskAuth, kioskMe);
router.get('/users', authMiddleware, listUsers);
router.put('/users/:id/access', authMiddleware, auditLog('users'), validate(idSchema, 'params'), validate(userAccessSchema), updateUserAccess);
export default router;
